package ru.highvibrations.browser;

/**
 * JavaScript для управления камерой со стороны приложения:
 *  - отслеживает поток getUserMedia (старт/остановка) и сообщает в Java;
 *  - умеет переключать камеру (front/back) и включать/выключать микрофон.
 * Внедряется на каждую загруженную страницу.
 */
public final class MediaScripts {

    private MediaScripts() {
    }

    public static String inject() {
        return "(function(){"
                + "if(window.__hvMedia){return;}window.__hvMedia=true;"
                + "var md=navigator.mediaDevices;"
                + "var st={stream:null,video:null,micMuted:false,facing:''};"
                + "function notify(){"
                + "try{HVMedia.onCameraActive(!!(st.video&&st.video.readyState==='live'));}catch(e){}"
                + "}"
                + "function track(stream){"
                + "if(!stream){return;}"
                + "st.stream=stream;"
                + "st.video=stream.getVideoTracks()[0]||null;"
                + "var a=stream.getAudioTracks()[0]||null;"
                + "st.micMuted=a?!a.enabled:false;"
                + "if(st.video){"
                + "st.video.onended=function(){st.video=null;notify();};"
                + "try{var s=st.video.getSettings?st.video.getSettings():{};"
                + "if(s&&s.deviceId){st.currentId=s.deviceId;}"
                + "if(s&&s.facingMode){st.facing=s.facingMode;"
                + "HVMedia.onCameraFacing(s.facingMode);}}catch(e){}"
                + "}"
                + "try{HVMedia.onMicMuted(st.micMuted);}catch(e){}"
                + "notify();"
                + "}"
                + "if(md&&md.getUserMedia){"
                + "var orig=md.getUserMedia.bind(md);"
                + "md.getUserMedia=function(c){return orig(c).then(function(s){track(s);return s;});};"
                + "}"
                + "function videos(){return Array.prototype.slice.call(document.querySelectorAll('video'));}"
                + "function active(){"
                + "var list=videos();"
                + "for(var i=0;i<list.length;i++){var s=list[i].srcObject;"
                + "if(s&&s.getVideoTracks&&s.getVideoTracks().length){return s;}}"
                + "return null;}"
                + "function current(){return st.stream||active();}"
                + "function swap(oldS,newS){videos().forEach(function(v){"
                + "if(v.srcObject===oldS){v.srcObject=newS;"
                + "if(v.play){try{v.play().catch(function(){});}catch(e){}}}});}"
                + "function pick(devices,other){"
                + "var cams=devices.filter(function(d){return d.kind==='videoinput';});"
                + "if(cams.length<2){return null;}"
                + "for(var i=0;i<cams.length;i++){if(cams[i].deviceId!==st.currentId){return cams[i];}}"
                + "return cams[0];}"
                + "window.__hvSwitchCamera=function(){"
                + "if(!st.stream){var a=active();if(a){track(a);}}"
                + "var cur=current();"
                + "if(!cur||!md||!md.enumerateDevices||!md.getUserMedia){return 'no-stream';}"
                + "var audio=cur.getAudioTracks()[0]||null;"
                + "var oldId=st.currentId||'';"
                + "function facingNow(){"
                + "try{return (st.video&&st.video.getSettings)?(st.video.getSettings().facingMode||''):'';}catch(e){return '';}}"
                + "var prev=facingNow()||st.facing||'';"
                + "function finish(ns,tag){"
                + "var v=ns.getVideoTracks()[0]||null;"
                + "var combined=new MediaStream();"
                + "if(v){combined.addTrack(v);}"
                + "if(audio){combined.addTrack(audio);}"
                + "swap(cur,combined);"
                + "st.stream=combined;st.video=v;"
                + "try{if(v&&v.getSettings&&v.getSettings().deviceId){st.currentId=v.getSettings().deviceId;}}catch(e){}"
                + "if(v){st.video.onended=function(){st.video=null;notify();};}"
                + "try{var f=(v&&v.getSettings&&v.getSettings().facingMode)||tag;"
                + "st.facing=f||st.facing;HVMedia.onCameraFacing(f||'');}catch(e){}"
                + "notify();"
                + "return 'ok';}"
                + "function open(c,tag){"
                + "var cv=st.video;if(cv){try{cv.stop();}catch(e){}}"
                + "return md.getUserMedia({audio:false,video:c}).then(function(ns){return finish(ns,tag);});}"
                + "return md.enumerateDevices().then(function(list){"
                + "var cams=list.filter(function(d){return d.kind==='videoinput';});"
                + "try{HVMedia.onCameraFacing('cams='+cams.length);}catch(e){}"
                + "if(cams.length<2){return 'single-camera';}"
                + "var i=0;"
                + "function next(){"
                + "while(i<cams.length&&cams[i].deviceId===oldId){i++;}"
                + "if(i>=cams.length){return 'no-more';}"
                + "var cand=cams[i++];"
                + "return open({deviceId:{ideal:cand.deviceId}},'device').then(function(r){"
                + "var f=facingNow();"
                + "if(prev&&f&&f===prev){return next();}"
                + "return r;"
                + "}).catch(function(e){try{HVMedia.onCameraFacing('err='+(e&&e.name));}catch(x){}"
                + "return next();});}"
                + "return next();"
                + "});"
                + "};"
                + "window.__hvToggleMic=function(){"
                + "if(!st.stream){var a=active();if(a){track(a);}}"
                + "if(!current()){return 'no-stream';}"
                + "var tracks=current().getAudioTracks();"
                + "if(!tracks.length){return 'no-audio';}"
                + "st.micMuted=!st.micMuted;"
                + "tracks.forEach(function(t){t.enabled=!st.micMuted;});"
                + "try{HVMedia.onMicMuted(st.micMuted);}catch(e){}"
                + "console.log('hv mic '+(st.micMuted?'muted':'on'));"
                + "return st.micMuted?'muted':'unmuted';"
                + "};"
                + "window.__hvMediaReport=function(){"
                + "if(!st.stream){var a=active();if(a){track(a);}}"
                + "notify();"
                + "try{HVMedia.onMicMuted(st.micMuted);}catch(e){}};"
                + "console.log('hv media ready');"
                + "window.__hvMediaReport();"
                + "var lastOn=false;"
                + "setInterval(function(){"
                + "var s=current();"
                + "var t=s&&s.getVideoTracks?s.getVideoTracks()[0]:null;"
                + "var on=!!(t&&t.readyState==='live');"
                + "if(on&&!st.stream){track(s);}"
                + "if(on!==lastOn){lastOn=on;notify();}"
                + "},700);"
                + "})();";
    }
}
